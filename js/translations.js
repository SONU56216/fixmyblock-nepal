export let currentLang = 'en';
export function getTranslation(key) { return translations[currentLang]?.[key] || key; }
export function setLanguage(lang) { if (translations[lang]) { currentLang = lang;
        localStorage.setItem('fixmyblock_lang', lang); return true; } return false; }
export function getCurrentLanguage() { return currentLang; }
export function loadSavedLanguage() { const saved = localStorage.getItem('fixmyblock_lang'); if (saved && translations[saved]) { currentLang =
            saved; } return currentLang; }